    'USERS',
    'MEMBERS',
    'AUTHORS',
    'CATEGORIES',
    'PUBLISHERS',
    'BOOKS',
    'BOOK_AUTHORS',
    'BOOK_COPIES',
    'LOANS',
    'FINES',
    'FINE_PAYMENTS',
    'BOOK_RESERVATIONS'
)
ORDER BY table_name, constraint_name;


