-- ============================================================
-- 1. USERS
-- Authentication and role management
-- ============================================================

CREATE TABLE users (
    user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username       VARCHAR2(50)  NOT NULL,
    password_hash  VARCHAR2(255) NOT NULL,
    role           VARCHAR2(20)  NOT NULL,
    full_name      VARCHAR2(100) NOT NULL,
    email          VARCHAR2(100) NOT NULL,
    status         VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    last_login     TIMESTAMP,

    CONSTRAINT pk_users
        PRIMARY KEY (user_id),

    CONSTRAINT uq_users_username
        UNIQUE (username),

    CONSTRAINT uq_users_email
        UNIQUE (email),

    CONSTRAINT ck_users_role
        CHECK (role IN ('ADMIN', 'LIBRARIAN', 'MEMBER')),

    CONSTRAINT ck_users_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);


-- ============================================================
-- 2. MEMBERS
-- Library member information
-- ============================================================

CREATE TABLE members (
    member_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER NOT NULL,
    membership_number  VARCHAR2(30) NOT NULL,
    phone              VARCHAR2(20) NOT NULL,
    address            VARCHAR2(250),
    join_date          DATE DEFAULT SYSDATE NOT NULL,
    membership_status  VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT pk_members
        PRIMARY KEY (member_id),

    CONSTRAINT uq_members_user
        UNIQUE (user_id),

    CONSTRAINT uq_members_number
        UNIQUE (membership_number),

    CONSTRAINT ck_members_status
        CHECK (membership_status IN ('ACTIVE', 'INACTIVE')),

    CONSTRAINT fk_members_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
);


-- ============================================================
-- 3. AUTHORS
-- Author master data
-- ============================================================

CREATE TABLE authors (
    author_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    author_name  VARCHAR2(150) NOT NULL,
    biography    CLOB,
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_authors
        PRIMARY KEY (author_id)
);


-- ============================================================
-- 4. CATEGORIES
-- Book category master data
-- ============================================================

CREATE TABLE categories (
    category_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    category_name  VARCHAR2(100) NOT NULL,
    description    VARCHAR2(500),
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_categories
        PRIMARY KEY (category_id),

    CONSTRAINT uq_categories_name
        UNIQUE (category_name)
);


-- ============================================================
-- 5. PUBLISHERS
-- Publisher master data
-- ============================================================

CREATE TABLE publishers (
    publisher_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    publisher_name  VARCHAR2(150) NOT NULL,
    email           VARCHAR2(100),
    phone           VARCHAR2(20),
    address         VARCHAR2(250),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_publishers
        PRIMARY KEY (publisher_id),

    CONSTRAINT uq_publishers_name
        UNIQUE (publisher_name),

    CONSTRAINT uq_publishers_email
        UNIQUE (email)
);


-- ============================================================
-- 6. BOOKS
-- Logical book/title information
-- ============================================================

CREATE TABLE books (
    book_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    isbn              VARCHAR2(20) NOT NULL,
    title             VARCHAR2(250) NOT NULL,
    category_id       NUMBER NOT NULL,
    publisher_id      NUMBER NOT NULL,
    publication_year  NUMBER(4),
    description       CLOB,
    keywords          VARCHAR2(1000),
    language          VARCHAR2(50) DEFAULT 'English' NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP,

    CONSTRAINT pk_books
        PRIMARY KEY (book_id),

    CONSTRAINT uq_books_isbn
        UNIQUE (isbn),

    CONSTRAINT fk_books_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id),

    CONSTRAINT fk_books_publisher
        FOREIGN KEY (publisher_id)
        REFERENCES publishers(publisher_id),

    CONSTRAINT ck_books_publication_year
        CHECK (
            publication_year IS NULL
            OR publication_year BETWEEN 1000 AND 9999
        )
);


-- ============================================================
-- 7. BOOK_AUTHORS
-- Junction table for BOOKS <-> AUTHORS
-- Many-to-many relationship
-- ============================================================

CREATE TABLE book_authors (
    book_id    NUMBER NOT NULL,
    author_id  NUMBER NOT NULL,

    CONSTRAINT pk_book_authors
        PRIMARY KEY (book_id, author_id),

    CONSTRAINT fk_book_authors_book
        FOREIGN KEY (book_id)
        REFERENCES books(book_id),

    CONSTRAINT fk_book_authors_author
        FOREIGN KEY (author_id)
        REFERENCES authors(author_id)
);


-- ============================================================
-- 8. BOOK_COPIES
-- Physical copy tracking
-- ============================================================

CREATE TABLE book_copies (
    copy_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    book_id          NUMBER NOT NULL,
    accession_number VARCHAR2(30) NOT NULL,
    barcode           VARCHAR2(50) NOT NULL,
    status            VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    shelf_location    VARCHAR2(50),
    acquisition_date  DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_book_copies
        PRIMARY KEY (copy_id),

    CONSTRAINT uq_book_copies_accession
        UNIQUE (accession_number),

    CONSTRAINT uq_book_copies_barcode
        UNIQUE (barcode),

    CONSTRAINT fk_book_copies_book
        FOREIGN KEY (book_id)
        REFERENCES books(book_id),

    CONSTRAINT ck_book_copies_status
        CHECK (
            status IN (
                'AVAILABLE',
                'ISSUED',
                'RESERVED',
                'DAMAGED',
                'LOST'
            )
        )
);


-- ============================================================
-- 9. LOANS
-- Book issue and return history
-- ============================================================

CREATE TABLE loans (
    loan_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    copy_id        NUMBER NOT NULL,
    member_id      NUMBER NOT NULL,
    issue_date     DATE DEFAULT SYSDATE NOT NULL,
    due_date       DATE NOT NULL,
    return_date    DATE,
    renewal_count  NUMBER DEFAULT 0 NOT NULL,
    status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT pk_loans
        PRIMARY KEY (loan_id),

    CONSTRAINT fk_loans_copy
        FOREIGN KEY (copy_id)
        REFERENCES book_copies(copy_id),

    CONSTRAINT fk_loans_member
        FOREIGN KEY (member_id)
        REFERENCES members(member_id),

    CONSTRAINT ck_loans_status
        CHECK (
            status IN (
                'ACTIVE',
                'RETURNED',
                'OVERDUE'
            )
        ),

    CONSTRAINT ck_loans_renewal
        CHECK (renewal_count >= 0),

    CONSTRAINT ck_loans_dates
        CHECK (due_date >= issue_date)
);


-- ============================================================
-- 10. FINES
-- Fine records associated with loans
-- ============================================================

CREATE TABLE fines (
    fine_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    loan_id       NUMBER NOT NULL,
    fine_amount   NUMBER(10,2) NOT NULL,
    reason        VARCHAR2(100) NOT NULL,
    fine_status   VARCHAR2(20) DEFAULT 'UNPAID' NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_fines
        PRIMARY KEY (fine_id),

    CONSTRAINT fk_fines_loan
        FOREIGN KEY (loan_id)
        REFERENCES loans(loan_id),

    CONSTRAINT ck_fines_amount
        CHECK (fine_amount > 0),

    CONSTRAINT ck_fines_status
        CHECK (
            fine_status IN (
                'UNPAID',
                'PARTIALLY_PAID',
                'PAID'
            )
        )
);


-- ============================================================
-- 11. FINE_PAYMENTS
-- Payment history for fines
-- ============================================================

CREATE TABLE fine_payments (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fine_id         NUMBER NOT NULL,
    payment_amount  NUMBER(10,2) NOT NULL,
    payment_date    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    payment_method  VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_fine_payments
        PRIMARY KEY (payment_id),

    CONSTRAINT fk_fine_payments_fine
        FOREIGN KEY (fine_id)
        REFERENCES fines(fine_id),

    CONSTRAINT ck_fine_payment_amount
        CHECK (payment_amount > 0),

    CONSTRAINT ck_fine_payment_method
        CHECK (
            payment_method IN (
                'CASH',
                'CARD',
                'UPI',
                'ONLINE'
            )
        )
);


-- ============================================================
-- 12. BOOK_RESERVATIONS
-- Book reservation management
-- ============================================================

CREATE TABLE book_reservations (
    reservation_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    book_id          NUMBER NOT NULL,
    member_id        NUMBER NOT NULL,
    reservation_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expiry_date      DATE,
    status           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT pk_book_reservations
        PRIMARY KEY (reservation_id),

    CONSTRAINT fk_reservations_book
        FOREIGN KEY (book_id)
        REFERENCES books(book_id),

    CONSTRAINT fk_reservations_member
        FOREIGN KEY (member_id)
        REFERENCES members(member_id),

    CONSTRAINT ck_reservations_status
        CHECK (
            status IN (
                'ACTIVE',
                'FULFILLED',
                'CANCELLED',
                'EXPIRED'
            )
        )
);


